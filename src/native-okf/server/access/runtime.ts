    NATIVE_OKF_MAX_GLOBAL_CONCURRENT:
      source.NATIVE_OKF_MAX_GLOBAL_CONCURRENT,
    NATIVE_OKF_HARD_DAILY_USD: source.NATIVE_OKF_HARD_DAILY_USD,
    NATIVE_OKF_HARD_MONTHLY_USD: source.NATIVE_OKF_HARD_MONTHLY_USD,
    NATIVE_OKF_TEST_HARD_DAILY_USD:
      source.NATIVE_OKF_TEST_HARD_DAILY_USD,
    NATIVE_OKF_TEST_HARD_MONTHLY_USD:
      source.NATIVE_OKF_TEST_HARD_MONTHLY_USD,
    NATIVE_OKF_RESEARCHER_SESSION_HOURS:
      source.NATIVE_OKF_RESEARCHER_SESSION_HOURS,
    NATIVE_OKF_ADMIN_SESSION_MINUTES:
      source.NATIVE_OKF_ADMIN_SESSION_MINUTES,
