    NATIVE_OKF_TRUSTED_PROXY_HEADER:
      source.NATIVE_OKF_TRUSTED_PROXY_HEADER,
    NATIVE_OKF_TRUSTED_PROXY_HOPS:
      source.NATIVE_OKF_TRUSTED_PROXY_HOPS,
    NATIVE_OKF_PUBLIC_ORIGIN: source.NATIVE_OKF_PUBLIC_ORIGIN,
